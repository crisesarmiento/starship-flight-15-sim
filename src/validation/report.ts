import data from '../../data/flight15.json'
import { norm, osculating, referenceAltitude, type Metrics } from './metrics'
import { type TimelineRow } from './timeline'

const format = (value: number | null | undefined, digits = 3) =>
  value != null && Number.isFinite(value) ? value.toFixed(digits) : '—'
const signed = (value: number) => !Number.isFinite(value)
  ? '—' : `${value < -0.0005 ? '-' : '+'}${format(Math.abs(value))}`
const asKm = (meters: number | null | undefined) => meters == null ? null : meters / 1000
const elapsed = (seconds: number) =>
  [Math.floor(seconds / 3600), Math.floor(seconds / 60) % 60, seconds % 60]
    .map(part => String(part).padStart(2, '0')).join(':')

function evidenceText(source: NonNullable<TimelineRow['clock']>, row: TimelineRow) {
  const { label, transitions } = source
  if (transitions.length === 0) return `${label}: not observed`
  if (transitions.length > 1) return `${label}: ambiguous (${transitions.map(x => format(x.time)).join(', ')} s)`
  const { time, before, after } = transitions[0]
  const error = time - row.time
  return `${label}: ${format(time)} s (${signed(error)} s${Math.abs(error) > row.tolerance ? ', out of tolerance' : ''})` +
    (source === row.clock ? '' : ` ${before === null ? 'start:' : `${before} →`} ${after}`)
}

function comparison(label: string, got: number | null, target: number, tolerance: number, unit: string) {
  const error = got == null ? null : got - target
  const result = error == null || !Number.isFinite(error) ? 'Not evaluable' : Math.abs(error) <= tolerance ? 'Within' : 'Outside'
  return `| ${label} | ${target} ${unit} | ${format(got)} | ${error == null ? '—' : signed(error)} | ±${tolerance} ${unit} | ${result} |`
}

type Datum = { confidence: string; value: unknown; unit?: string; source: string; note?: string }
function* datums(node: unknown, path = ''): Generator<[string, Datum]> {
  if (node == null || typeof node !== 'object') return
  if ('confidence' in node && 'value' in node) {
    yield [path, node as Datum]
    return
  }
  for (const [key, value] of Object.entries(node)) {
    const name = Array.isArray(node) && value?.id ? value.id : key
    yield* datums(value, path ? `${path}.${name}` : name)
  }
}
const cell = (value: string) => value.replaceAll('|', '\\|').replaceAll('\n', ' ')
const sourceLink = (source: string) => source.replace(/^docs\//, '')

export function renderReport(rows: TimelineRow[], metrics: Metrics) {
  const { staging, stagingRawM, insertionBefore, insertionAfter, deorbitBefore, deorbitAfter, entry, hover, caught } = metrics
  const cut = metrics.entryCut
  const dataRows = [...datums(data)]
  const estimates = dataRows.filter(([, datum]) => datum.confidence === 'estimate')
  const unknowns = dataRows.filter(([, datum]) => datum.confidence === 'unknown')
  const stagingSource = data.timeline.find(event => event.id === 'hot_staging')!.altitude_m!.source
  const orbitSource = data.mission.orbit.altitude_km.source
  const insertionDeltaV = data.mission.orbit.insertion_delta_v_m_s
  const perigee = (state: typeof insertionAfter) => format(asKm(state?.orbit.perigeeM))
  const actual = (state: typeof staging) => format(asKm(state?.ship.altitudeM))
  return [
    '# Validation — Starship Flight 15',
    '',
    '<!-- Generated by src/validation. Do not edit by hand. -->',
    '',
    'Educational approximation built from public data. It is not telemetry or an operational validation.',
    '',
    'To regenerate: `UPDATE_REPORT=1 npm test -- src/validation`. Without `UPDATE_REPORT=1`, the test does not write the file.',
    '',
    '## Timeline: imposed clock (reloj impuesto)',
    '',
    'Public reference table, kept separate from the simulator schedule: [SPEC §2 and §8](SPEC.md) and [copy of the public table in research §3](research.md#3-línea-de-tiempo-oficial-copia-de-trabajo).',
    'There are 26 approximate public milestones plus one extra FTS row: the account places the FTS at cutoff, without publishing an independent second.',
    'The clock is imposed; ignitions, cutoffs, deployment and final states are also driven by the program. Measuring when their output changes checks the implementation, not a physical prediction of those times.',
    'Max Q, return checks, entry, transonic, subsonic and flip are compared as phase markers: they are not physical detections of dynamic pressure, Mach or attitude.',
    'Each reference is sampled every 0.25 s (±tolerance plus 2 s) and every detected transition is refined by bisection; at T+0 the initial state is observed.',
    'Timing offsets are **observed − reference**. A marker with no transition, or an ambiguous one, does not count as passed.',
    '',
    '| Milestone | Public T+ (s) | Tolerance | Imposed clock: measured marker (Δs) | Effects observed in `sample` (Δs) |',
    '| --- | ---: | ---: | --- | --- |',
    ...rows.map(row => `| \`${row.id}\` | ${elapsed(row.time)} (${row.time}) | ±${row.tolerance} s | ` +
      `${row.clock ? evidenceText(row.clock, row) : 'Shared with FTS'} | ` +
      `${row.effects.map(effect => evidenceText(effect, row)).join('; ') || 'Marker only'} |`),
    '',
    '## Trajectory prediction: raw staging only',
    '',
    'Drag uses tabulated densities from the U.S. Standard Atmosphere 1976 (Table II), with logarithmic interpolation up to 86 km. Above that, the last slope is extrapolated: it is not the upper atmosphere of the standard model.',
    '',
    `The raw integrated staging altitude, evaluated at the imposed staging time before the radial correction, is the only trajectory prediction compared against a reported value here. The residual is raw altitude minus the [reported staging altitude of 65 km](${stagingSource}); it is not an error measured against telemetry. The ±10 km tolerance comes from [SPEC §8](SPEC.md#8-validation-criteria).`,
    '',
    '| Quantity | Reference | Simulated (km) | Residual (km) | Tolerance | Result |',
    '| --- | ---: | ---: | ---: | ---: | --- |',
    comparison('Raw staging, before guidance', asKm(stagingRawM), referenceAltitude.staging / 1000, 10, 'km'),
    '',
    '## Trajectory anchors (anclas)',
    '',
    `The [reported staging altitude of 65 km](${stagingSource}) is imposed by the radial correction. The [reported orbital altitude of 275 km](${orbitSource}) sets the circular post-insertion orbit, so its perigee also follows from that anchor. Agreement checks that the model applies its inputs; it is not a trajectory prediction.`,
    '',
    '| Quantity | Anchor input | Simulated output (km) |',
    '| --- | ---: | ---: |',
    `| Adjusted staging altitude at Ship ignition | ${referenceAltitude.staging / 1000} km | ${actual(staging)} |`,
    `| Altitude immediately after insertion cutoff | ${referenceAltitude.orbit / 1000} km | ${actual(insertionAfter)} |`,
    `| Perigee immediately after insertion cutoff (derived from the anchored orbit) | ${referenceAltitude.orbit / 1000} km | ${perigee(insertionAfter)} |`,
    '',
    '## Orbital consistency checks',
    '',
    'Recomputing orbital elements from the simulated ECI state and checking the direction of change through each burn test internal consistency, not agreement with the actual flight.',
    '',
    `Osculating perigee during insertion: **${perigee(insertionBefore)} → ${perigee(insertionAfter)} km**; during deorbit: **${perigee(deorbitBefore)} → ${perigee(deorbitAfter)} km**. Altitude at the entry marker: ${actual(entry)} km.`,
    `Perigee reported by McDowell: ~${data.mission.orbit.mcdowell_perigee_km.value} km (via Wikipedia, see [research §2](research.md#ship-como-voló)); it is not an additional official reference.`,
    ...(insertionAfter ? [
      `After insertion, the ECI state gives a perigee of ${format(asKm(osculating(insertionAfter.ship).perigeeM))} km when recomputed with μ WGS 84. The simulator reports apogee ${format(asKm(insertionAfter.orbit.apogeeM))} km, inclination ${format(insertionAfter.orbit.inclinationDeg)}°, period ${format(insertionAfter.orbit.periodS)} s and eccentricity ${format(insertionAfter.orbit.eccentricity, 6)} (no validated flight reference).`,
    ] : []),
    '',
    '## Cinematic cut at entry',
    '',
    `At T+${format(cut.time)} s the model goes from the Keplerian coast to a local cinematic leg. The jump is computed between the simulator's two ECI states at that same instant:`,
    '',
    `- Displacement \`‖r after − r before‖\`: **${format(asKm(cut.measuredDistanceM))} km**.`,
    `- Velocity vector difference \`‖v after − v before‖\`: **${format(cut.measuredVelocityGapMs)} m/s** (inertial speeds: ${format(norm(cut.before.v))} → ${format(norm(cut.after.v))} m/s).`,
    '',
    'It is a deliberate discontinuity of the model, not a residual against telemetry or the Δv of a burn. There is no published limit to compare these jumps against: the test checks the instant and the states, and does not require physical continuity. The later leg does not allow inferring the real corridor, the loads at the transition or the aerothermal stresses.',
    '',
    '## Observed outcome',
    '',
    `- Booster just before the FTS: altitude ${format(hover?.booster.altitudeM)} m, ground-relative speed ${format(hover?.booster.surfaceSpeedMs)} m/s, distance to Pad 2 ${format(asKm(metrics.hoverSite?.padDistanceM))} km, ` +
      `${metrics.hoverSite ? (metrics.hoverSite.eastOfPad ? 'east of the pad' : 'not east of the pad') : 'bearing not evaluable'}. The eastward displacement, low altitude and low speed are qualitative checks of the divert and hover, not real coordinates or a cartographic proof of the coast.`,
    `- Booster at FTS: status \`${metrics.fts?.booster.status ?? 'not observed'}\`, engines ${metrics.fts?.boosterEngines ?? '—'}. The incorrect catch label from the public table is not used.`,
    `- Ship at the catch: status \`${caught?.ship.status ?? 'not observed'}\`, engines ${caught?.shipEngines ?? '—'}, horizontal distance to Pad 2 ${format(metrics.catchSite?.padDistanceM)} m (ECI converted to Earth-fixed). The actual arm height is not published.`,
    '',
    '## Δv of the maneuvers',
    '',
    `Model estimates and inputs, not telemetry. The [92 m/s insertion Δv reported by McDowell (via Wikipedia)](${insertionDeltaV.source}) is an anchor (ancla), not a predicted value. A dash means the model does not report a Δv for that maneuver.`,
    '',
    '| Maneuver | Model Δv (m/s) | Model role |',
    '| --- | ---: | --- |',
    ...metrics.burns.map(({ id, deltaV }) => {
      const role = id === 'insertion_start' ? `Anchor: ~${insertionDeltaV.value} m/s (McDowell, reported)`
        : deltaV === null ? 'Not evaluable: the model reports no Δv' : 'Estimate: no published reference'
      return `| \`${id}\` | ${format(deltaV)} | ${role} |`
    }),
    '',
    '## Estimates declared in `data/flight15.json`',
    '',
    '| Parameter | Value | Confidence | Source / note |',
    '| --- | --- | --- | --- |',
    ...estimates.map(([path, datum]) => `| \`${path}\` | ${cell(String(datum.value))} ${datum.unit ?? ''} | estimate | ` +
      `[Source](${sourceLink(datum.source)})${datum.note ? `: ${cell(datum.note)}` : ''} |`),
    ...(estimates.length ? [] : ['| — | — | — | There are no entries marked `estimate`. |']),
    '',
    '## Unknown data: not evaluable',
    '',
    'A simulated value for a quantity with no published reference does not fill in the `null` and is not considered official. See also the untabulated gaps in [research §5](research.md#5-qué-no-apareció-huecos-que-importan-al-sim).',
    'UI check (manual, not covered by this test): in the HUD, no `unknown` quantity may carry the “Official” label; if a model value is shown, it must indicate that it is estimated, interpolated or calculated.',
    '',
    '| JSON field | Status | Note |',
    '| --- | --- | --- |',
    ...unknowns.map(([path, datum]) => `| \`${path}\` | \`unknown\` / not evaluable | ${cell(datum.note ?? datum.source)} |`),
    '',
  ].join('\n')
}
